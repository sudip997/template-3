/* -------------------------------------------------------------------------
 * Rasterising
 * ---------------------------------------------------------------------- */

const parseRing = (text) =>
  text
    .trim()
    .split(/\s+/)
    .map((pair) => pair.split(",").map(Number));

/** Even-odd test: is (x, y) inside the ring? */
function contains(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/** True if any ring holds the point, also trying the wrapped-around copy. */
const anyContains = (rings, lon, lat) =>
  rings.some((ring) => contains(ring, lon, lat) || contains(ring, lon + 360, lat));

function loadShapes(geojsonPath) {
  if (!geojsonPath) {
    return {
      land: Object.values(LAND).map(parseRing),
      water: Object.values(WATER).map(parseRing),
    };
  }

  const data = JSON.parse(readFileSync(geojsonPath, "utf8"));
  const features = data.type === "FeatureCollection" ? data.features : [data];
  const land = [];
  const water = [];

  for (const feature of features) {
    const geometry = feature.type === "Feature" ? feature.geometry : feature;
    const polygons =
      geometry.type === "Polygon"
        ? [geometry.coordinates]
        : geometry.type === "MultiPolygon"
          ? geometry.coordinates
          : [];
    for (const [outer, ...holes] of polygons) {
      land.push(outer);
      water.push(...holes);
    }
  }
  return { land, water };
}

function rasterise({ land, water }) {
  // Row 0 is the band 90°N to 89°N; column 0 is 180°W to 179°W.
  const rows = [];
  for (let row = 0; row < HEIGHT; row += 1) {
    const lat = 90 - row - 0.5;
    const cells = [];
    for (let col = 0; col < WIDTH; col += 1) {
      const lon = -180 + col + 0.5;
      cells.push(anyContains(land, lon, lat) && !anyContains(water, lon, lat));
    }
    rows.push(cells);
  }
  return rows;
}

/** "water,land,water,..." run lengths, always starting with water. */
function encodeRow(cells) {
  const runs = [];
  let current = false;
  let length = 0;
  for (const cell of cells) {
    if (cell === current) {
      length += 1;
    } else {
      runs.push(length);
      current = cell;
      length = 1;
    }
  }
  runs.push(length);
  return runs.join(",");
}

/* -------------------------------------------------------------------------
 * Output
 * ---------------------------------------------------------------------- */

const source = process.argv[2] ? resolve(process.argv[2]) : null;
const grid = rasterise(loadShapes(source));
const encoded = grid.map(encodeRow);

// Share of the sphere's surface that is land: weight each row by its width
// on the ground (the cosine of its latitude), since polar cells are tiny.
let landArea = 0;
let totalArea = 0;
grid.forEach((cells, row) => {
  const weight = Math.cos(((90 - row - 0.5) * Math.PI) / 180);
  landArea += cells.filter(Boolean).length * weight;
  totalArea += cells.length * weight;
});

